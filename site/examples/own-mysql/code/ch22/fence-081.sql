SELECT ENGINE,REQUESTING_ENGINE_TRANSACTION_ID,BLOCKING_ENGINE_TRANSACTION_ID
FROM performance_schema.data_lock_waits;
SELECT ENGINE_TRANSACTION_ID,THREAD_ID,OBJECT_SCHEMA,OBJECT_NAME,
       INDEX_NAME,LOCK_TYPE,LOCK_MODE,LOCK_STATUS,LOCK_DATA
FROM performance_schema.data_locks
WHERE OBJECT_SCHEMA='mysql_tx_lab';
SELECT OBJECT_TYPE,OBJECT_SCHEMA,OBJECT_NAME,LOCK_TYPE,LOCK_DURATION,
       LOCK_STATUS,OWNER_THREAD_ID
FROM performance_schema.metadata_locks
WHERE OBJECT_SCHEMA='mysql_tx_lab';
SELECT THREAD_ID,PROCESSLIST_ID,PROCESSLIST_INFO
FROM performance_schema.threads
WHERE PROCESSLIST_ID IS NOT NULL;
SHOW ENGINE INNODB STATUS;
