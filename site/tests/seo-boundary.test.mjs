import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {readPracticeBoundaryCorrections,projectPracticeBoundaryCorrections as project} from '../scripts/practice-boundary-corrections.mjs';
const sha=value=>createHash('sha256').update(value).digest('hex');
const json=async file=>JSON.parse(await readFile(new URL('../'+file,import.meta.url),'utf8'));
const registry=await readPracticeBoundaryCorrections(),catalog=await json('dist/data/catalog.json'),byId=new Map();
for(const file of new Set(catalog.entries.map(entry=>entry._chunk)))for(const entry of (await json('dist/'+file)).entries)byId.set(entry.id,entry);
const entries=catalog.entries.map(entry=>byId.get(entry.id));
const record=registry.postReviewRecords.find(record=>record.review.purpose==='backend-boundary-archive');
test('SEO specialist subsection alone is replaced by the reviewed backend boundary without changing identity or the rest of the answer',()=>{
  assert.equal(record.beforeSha256,'46479c1fb0036b77ddb81095f1f75c193fa0a5ae9f16a5a554be72c5662fe580');
  assert.equal(record.afterSha256,'4a8ac2c44f961e48a7994f534414f85a8a1e6e2f9a75f35b9b84a8a3b6b0733b');
  const edit=record.edits[0];assert.equal(record.edits.length,1);
  assert.equal(record.before.split(edit.beforeHtml).length,2);
  assert.equal(record.before.replace(edit.beforeHtml,edit.afterHtml),record.after);
  assert.equal(sha(record.after),record.afterSha256);
  assert.ok(record.after.includes('发布版本与时间'));
  assert.ok(record.after.includes('不能把排名变化全部归因于数据库优化'));
  assert.ok(!record.after.includes(edit.beforeHtml));
  const question=byId.get(record.entryId).items[0];
  assert.equal(question.id,'q-own-practice-client-server-timing');
  assert.equal(question.a,record.after);
  const original=project(entries,registry,{reverse:true}).find(entry=>entry.id===record.entryId).items[0];
  assert.deepEqual({...question,a:undefined},{...original,a:undefined});
  assert.equal(original.a,record.before);
  const refs=html=>[...html.matchAll(/\b(?:id|href)="[^"]*"/g)].map(match=>match[0]);
  assert.deepEqual(refs(record.after),refs(record.before));
  assert.equal(record.review.archive.fileSha256,'9c230a4e11018b9a1d629e95c04ade65da493a9a37ce4268a5a3acac8e81747b');
  assert.equal(record.review.archive.archiveMustRemainOutsideSiteHtml,true);
});
test('obsolete SEO section is absent from delivered entries/search/archive while the final layer remains reversible and baseline-excluded',async()=>{
  const originalSection=record.edits[0].beforeHtml;
  assert.ok(!JSON.stringify(entries).includes(JSON.stringify(originalSection).slice(1,-1)));
  for(const file of ['dist/data/search.json','dist/data/archives/source-entries.json'])assert.ok(!(await readFile(new URL('../'+file,import.meta.url),'utf8')).includes('SEO 怎样测，而不是只看页面快不快'));
  const before=project(entries,registry,{reverse:true});
  assert.deepEqual(project(before,registry),entries);
  assert.equal(project(before,null,{baselineTest:true}),before);
  const changed=structuredClone(before);changed.find(entry=>entry.id===record.entryId).items[0].a+='stale';
  assert.throws(()=>project(changed,registry),/stale input/);
});
