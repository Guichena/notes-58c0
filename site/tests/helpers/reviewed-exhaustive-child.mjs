import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {freezeStableRegistry} from './immutable-registry-fixture.mjs';
import {projectReviewedContent,REVIEWED_CONTENT_SHA256} from '../../scripts/reviewed-content-projection.mjs';
import {projectInterviewEditorial} from '../../scripts/interview-editorial-projection.mjs';
import {upstream} from './editorial-upstream.mjs';
import {runGlobalChecks,runRangeChecks} from './reviewed-exhaustive-assertions.mjs';
import {digest,recordID,validateReceipt} from './reviewed-exhaustive-coverage.mjs';
const [mode,startText,endText,expectedHash]=process.argv.slice(2),start=Number(startText),end=Number(endText);
assert.ok(['globals','range'].includes(mode));
const root=new URL('../../',import.meta.url),json=async p=>JSON.parse(await readFile(new URL(p,root),'utf8'));
const registry=freezeStableRegistry(await json('content/reviewed-content-projection.json'));
assert.equal(digest(registry),expectedHash);assert.equal(expectedHash,REVIEWED_CONTENT_SHA256);
assert.ok(Number.isInteger(start)&&Number.isInteger(end)&&start>=0&&end>=start&&end<=registry.records.length);
assert.ok(mode==='globals'?start===0&&end===0:end>start&&end-start<=50);
const input=projectInterviewEditorial(upstream.claimEntries,await json('content/interview-editorial-projection.json'));
const output=projectReviewedContent(input,registry),get=(e,p)=>p.reduce((x,k)=>x[k],e);
const context={input,output,registry,projectReviewedContent,get};
const globalChecks=mode==='globals'?runGlobalChecks(context):[];
if(mode==='range')runRangeChecks(context,start,end);
const records=mode==='globals'?[]:registry.records.slice(start,end).map((r,i)=>recordID(r,start+i));
const receipt={terminal:true,mode,start,end,registrySHA256:expectedHash,records,globalChecks,calls:records.reduce((n,r)=>n+r.checks.length,0)+globalChecks.length};
validateReceipt(receipt,{registrySHA256:expectedHash,records:registry.records,start,end,mode});
console.log(JSON.stringify(receipt));
